def humanize(name: str) -> str:
    special = {
        "mae": "MAE",
        "rmse": "RMSE",
        "r2": "R-squared",
        "r_squared": "R-squared",
        "se": "SE",
        "ci": "CI",
        "p": "p Value",
        "p_value": "p Value",
        "p_value_normal": "p Value (Normal)",
        "z": "z Statistic",
        "z_statistic": "z Statistic",
        "sha256": "SHA-256",
        "n": "N",
        "n_clusters": "Number of Hotel Clusters",
        "bootstrap_ci_low": "Bootstrap 95% CI Lower",
        "bootstrap_ci_high": "Bootstrap 95% CI Upper",
        "cluster_robust_se": "Cluster-Robust SE",
        "offering_id": "Hotel ID",
        "row_id": "Row ID",
        "ok_rate": "Schema-Valid Rate",
    }
    if name in special:
        return special[name]
    words = name.replace("__", " ").replace("_", " ").split()
    acronyms = {"cv": "CV", "icc": "ICC", "sd": "SD", "id": "ID", "json": "JSON"}
    return " ".join(acronyms.get(word.lower(), word.capitalize()) for word in words)


def publication_columns(df: pd.DataFrame, overrides: dict[str, str] | None = None) -> pd.DataFrame:
    overrides = overrides or {}
    return df.rename(columns={column: overrides.get(column, humanize(column)) for column in df.columns})


def clean_excel_frame(df: pd.DataFrame) -> pd.DataFrame:
    result = df.copy()
    result = result.replace([np.inf, -np.inf], np.nan)
    for column in result.columns:
        if result[column].dtype == object:
            result[column] = result[column].map(
                lambda value: json.dumps(value, ensure_ascii=False)
                if isinstance(value, (dict, list, tuple))
                else value
            )
    return result


