def protocol_sensitivity() -> pd.DataFrame:
    r_table = read_csv("outputs/phase2/experiment_r_model_summary.csv")
    keep = r_table[r_table["model_id"].astype(str).str.startswith(("phase2_r0_", "phase2_r1b_", "phase2_r1c_"))].copy()
    keep.insert(0, "protocol", keep["model_id"].str.extract(r"phase2_(r0|r1b|r1c)", expand=False).str.upper())
    keep["display_name"] = keep["model_id"]
    keep = keep.rename(columns={"mae_std": "mae_sd", "rmse_std": "rmse_sd"})

    panel_b = read_csv("outputs/phase4/u1_panel_b_u0.csv")
    u0 = panel_b[panel_b["model"].isin(["text_only", "simple_fusion", "interaction_fusion"])].copy()
    u0["protocol"] = "U0"
    desired = ["protocol", "model_id", "display_name", "mae_mean", "mae_sd", "rmse_mean", "rmse_sd"]
    return pd.concat([keep.reindex(columns=desired), u0.reindex(columns=desired)], ignore_index=True)


