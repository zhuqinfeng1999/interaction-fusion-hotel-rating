def build_inventory() -> pd.DataFrame:
    records = []
    for path in sorted(ROOT.rglob("*")):
        if not path.is_file() or ".git" in path.relative_to(ROOT).parts:
            continue
        classification, justification = classify(path)
        records.append({
            "path": path.relative_to(ROOT).as_posix(),
            "bytes": path.stat().st_size,
            "file_type": file_type(path),
            "proposed_class": classification,
            "justification": justification,
        })
    return pd.DataFrame(records)


def inventory_summary(inventory: pd.DataFrame) -> pd.DataFrame:
    order = ["CODE", "DATA_CORE", "DATA_OPTIONAL", "REGENERABLE", "WEIGHTS", "UPSTREAM", "EXPLORATORY"]
    summary = inventory.groupby("proposed_class", as_index=False).agg(file_count=("path", "count"), total_bytes=("bytes", "sum"))
    summary["gib"] = summary["total_bytes"] / (1024 ** 3)
    summary["sort"] = summary["proposed_class"].map({name: index for index, name in enumerate(order)})
    return summary.sort_values("sort").drop(columns="sort")


