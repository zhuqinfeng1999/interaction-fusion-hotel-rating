def scan_schema_and_evidence() -> dict[str, Any]:
    """Scan the complete Qwen extraction once; do not write or alter extraction caches."""
    aspect_path = OUTPUTS / "aspects_llm_qwen25_7b.parquet"
    dataset_path = OUTPUTS / "dataset_clean.parquet"
    if not aspect_path.exists() or not dataset_path.exists():
        raise FileNotFoundError("full Qwen aspect parquet and cleaned dataset are required")

    aspect_file = pq.ParquetFile(aspect_path)
    dataset_file = pq.ParquetFile(dataset_path)
    schema_names = set(aspect_file.schema_arrow.names)
    offset_columns = sorted(
        name for name in schema_names
        if re.search(r"(^|_)(start|end|offset|span_start|span_end)($|_)", name.lower())
    )
    score_columns = [f"aspect_{aspect}_score" for aspect in ASPECTS]
    mention_columns = [f"aspect_{aspect}_mentioned" for aspect in ASPECTS]
    required = ["row_id", "ok", "response_json", *score_columns, *mention_columns]
    missing = [column for column in required if column not in schema_names]
    if missing:
        raise ValueError(f"full aspect parquet lacks required columns: {missing}")

    rows = ok_rows = structured_valid = response_valid = 0
    mention_counts = Counter()
    score_out_of_range = Counter()
    evidence_count = evidence_chars = evidence_utf8_bytes = 0
    case_sensitive_hits = normalized_hits = ambiguous_hits = 0
    per_aspect_total = Counter()
    per_aspect_normalized_hits = Counter()
    row_ids = array("I")
    aspect_ids = array("B")
    evidence_ranks = array("B")
    starts = array("i")
    ends = array("i")
    matched = array("B")

    aspect_batches = aspect_file.iter_batches(batch_size=25_000, columns=required)
    text_batches = dataset_file.iter_batches(batch_size=25_000, columns=["review_text"])
    for aspect_batch, text_batch in zip(aspect_batches, text_batches, strict=True):
        data = aspect_batch.to_pydict()
        texts = text_batch.column(0).to_pylist()
        batch_n = aspect_batch.num_rows
        if len(texts) != batch_n:
            raise AssertionError("aspect and review batches are not aligned")
        for local_index in range(batch_n):
            row_id = int(data["row_id"][local_index])
            if row_id != rows + local_index:
                raise AssertionError(f"unexpected row order: row_id={row_id}, expected={rows + local_index}")
            is_ok = int(data["ok"][local_index] or 0) == 1
            ok_rows += int(is_ok)
            structured_row_valid = True
            for aspect, score_column, mention_column in zip(ASPECTS, score_columns, mention_columns):
                score = data[score_column][local_index]
                mention = data[mention_column][local_index]
                if score is None or float(score) < -2 or float(score) > 2:
                    score_out_of_range[aspect] += 1
                    structured_row_valid = False
                if mention is None or not isinstance(mention, (bool, np.bool_)):
                    structured_row_valid = False
                mention_counts[aspect] += int(bool(mention))
            structured_valid += int(structured_row_valid)

            raw_json = data["response_json"][local_index]
            try:
                parsed = json.loads(raw_json) if isinstance(raw_json, str) else raw_json
                parsed_aspects = parsed.get("aspects", {}) if isinstance(parsed, dict) else {}
                valid_json = isinstance(parsed_aspects, dict)
            except (json.JSONDecodeError, TypeError, AttributeError):
                parsed_aspects = {}
                valid_json = False
            response_valid += int(valid_json)
            if not is_ok or not valid_json:
                continue

            text = str(texts[local_index] or "")
            lower_text = text.lower()
            for aspect_index, aspect in enumerate(ASPECTS):
                payload = parsed_aspects.get(aspect, {})
                evidence = payload.get("evidence", []) if isinstance(payload, dict) else []
                if not isinstance(evidence, list):
                    continue
                for rank, value in enumerate(evidence[:2]):
                    if not isinstance(value, str) or not value.strip():
                        continue
                    snippet = value.strip()
                    evidence_count += 1
                    per_aspect_total[aspect] += 1
                    evidence_chars += len(snippet)
                    evidence_utf8_bytes += len(snippet.encode("utf-8"))
                    cs_start = text.find(snippet)
                    if cs_start >= 0:
                        start = cs_start
                        case_sensitive_hits += 1
                    else:
                        start = lower_text.find(snippet.lower())
                    is_match = start >= 0
                    normalized_hits += int(is_match)
                    per_aspect_normalized_hits[aspect] += int(is_match)
                    if is_match and lower_text.find(snippet.lower(), start + 1) >= 0:
                        ambiguous_hits += 1
                    row_ids.append(row_id)
                    aspect_ids.append(aspect_index)
                    evidence_ranks.append(rank)
                    starts.append(start if is_match else -1)
                    ends.append(start + len(snippet) if is_match else -1)
                    matched.append(int(is_match))
        rows += batch_n
        if rows % 100_000 < batch_n:
            log(f"  evidence/schema scan: {rows:,}/{aspect_file.metadata.num_rows:,} rows")

    if rows != aspect_file.metadata.num_rows or rows != dataset_file.metadata.num_rows:
        raise AssertionError("full-corpus row counts differ")
    if evidence_count != len(row_ids):
        raise AssertionError("offset-array length does not match evidence count")

    offsets_table = pa.table(
        {
            "row_id": pa.array(row_ids, type=pa.uint32()),
            "aspect_id": pa.array(aspect_ids, type=pa.uint8()),
            "evidence_rank": pa.array(evidence_ranks, type=pa.uint8()),
            "start": pa.array(starts, type=pa.int32()),
            "end": pa.array(ends, type=pa.int32()),
            "matched": pa.array(np.frombuffer(matched, dtype=np.uint8).astype(bool), type=pa.bool_()),
        }
    )
    offsets_arrow_bytes = offsets_table.nbytes
    with tempfile.TemporaryDirectory(prefix="phase6a_offsets_") as temporary_directory:
        temporary_path = Path(temporary_directory) / "evidence_offsets.parquet"
        pq.write_table(offsets_table, temporary_path, compression="zstd")
        offsets_parquet_bytes = temporary_path.stat().st_size

    cache_schemas: dict[str, list[str]] = {}
    cache_offset_columns: dict[str, list[str]] = {}
    for cache_path in sorted((OUTPUTS / "llm_cache").rglob("cache.sqlite")):
        connection = sqlite3.connect(f"file:{cache_path}?mode=ro", uri=True)
        try:
            columns = [row[1] for row in connection.execute("PRAGMA table_info(cache)")]
        finally:
            connection.close()
        relative = cache_path.relative_to(ROOT).as_posix()
        cache_schemas[relative] = columns
        cache_offset_columns[relative] = [
            column for column in columns
            if any(token in column.lower() for token in ("offset", "start", "end"))
        ]

    return {
        "rows": rows,
        "ok_rows": ok_rows,
        "ok_rate": ok_rows / rows,
        "structured_valid_rows": structured_valid,
        "structured_valid_rate": structured_valid / rows,
        "response_json_valid_rows": response_valid,
        "mention_counts": dict(mention_counts),
        "mention_rates": {aspect: mention_counts[aspect] / rows for aspect in ASPECTS},
        "score_out_of_range": dict(score_out_of_range),
        "evidence_items": evidence_count,
        "evidence_characters": evidence_chars,
        "evidence_utf8_bytes": evidence_utf8_bytes,
        "case_sensitive_hits": case_sensitive_hits,
        "case_sensitive_hit_rate": case_sensitive_hits / evidence_count,
        "normalized_exact_hits": normalized_hits,
        "normalized_exact_hit_rate": normalized_hits / evidence_count,
        "ambiguous_normalized_hits": ambiguous_hits,
        "per_aspect_evidence_total": dict(per_aspect_total),
        "per_aspect_normalized_hits": dict(per_aspect_normalized_hits),
        "offset_columns_in_parquet": offset_columns,
        "cache_schemas": cache_schemas,
        "cache_offset_columns": cache_offset_columns,
        "offsets_arrow_bytes": offsets_arrow_bytes,
        "offsets_parquet_zstd_bytes": offsets_parquet_bytes,
        "offset_schema": "row_id:uint32, aspect_id:uint8, evidence_rank:uint8, start:int32, end:int32, matched:bool",
    }


def scan_guided_qwen_reference() -> dict[str, Any]:
    """Reproduce the accepted 983,771-item evidence denominator on the L1 sample."""
    guided_path = OUTPUTS / "phase3/aspects_guided_qwen25_7b_l1_n200041.parquet"
    dataset_path = OUTPUTS / "dataset_clean.parquet"
    guided = pd.read_parquet(guided_path, columns=["row_id", "ok", "response_json"])
    if guided["row_id"].duplicated().any():
        raise AssertionError("guided Qwen reference has duplicate row_id values")
    all_texts = pd.read_parquet(dataset_path, columns=["review_text"])["review_text"]
    selected_texts = all_texts.iloc[guided["row_id"].astype(np.int64).to_numpy()].fillna("").astype(str).tolist()

    item_count = characters = utf8_bytes = case_sensitive_hits = normalized_hits = ambiguous_hits = 0
    row_ids = array("I")
    aspect_ids = array("B")
    evidence_ranks = array("B")
    starts = array("i")
    ends = array("i")
    matched = array("B")
    for index, (record, text) in enumerate(zip(guided.itertuples(index=False), selected_texts, strict=True), start=1):
        if int(record.ok or 0) != 1:
            continue
        try:
            parsed = json.loads(str(record.response_json))
        except (json.JSONDecodeError, TypeError):
            continue
        payloads = parsed.get("aspects", {}) if isinstance(parsed, dict) else {}
        lower_text = text.lower()
        for aspect_index, aspect in enumerate(ASPECTS):
            payload = payloads.get(aspect, {}) if isinstance(payloads, dict) else {}
            values = payload.get("evidence", []) if isinstance(payload, dict) else []
            if not isinstance(values, list):
                continue
            for rank, value in enumerate(values[:2]):
                snippet = str(value).strip()
                if not snippet:
                    continue
                item_count += 1
                characters += len(snippet)
                utf8_bytes += len(snippet.encode("utf-8"))
                cs_start = text.find(snippet)
                if cs_start >= 0:
                    start = cs_start
                    case_sensitive_hits += 1
                else:
                    start = lower_text.find(snippet.lower())
                is_match = start >= 0
                normalized_hits += int(is_match)
                ambiguous_hits += int(is_match and lower_text.find(snippet.lower(), start + 1) >= 0)
                row_ids.append(int(record.row_id))
                aspect_ids.append(aspect_index)
                evidence_ranks.append(rank)
                starts.append(start if is_match else -1)
                ends.append(start + len(snippet) if is_match else -1)
                matched.append(int(is_match))
        if index % 50_000 == 0:
            log(f"  guided-reference evidence scan: {index:,}/{len(guided):,} rows")

    offsets_table = pa.table(
        {
            "row_id": pa.array(row_ids, type=pa.uint32()),
            "aspect_id": pa.array(aspect_ids, type=pa.uint8()),
            "evidence_rank": pa.array(evidence_ranks, type=pa.uint8()),
            "start": pa.array(starts, type=pa.int32()),
            "end": pa.array(ends, type=pa.int32()),
            "matched": pa.array(np.frombuffer(matched, dtype=np.uint8).astype(bool), type=pa.bool_()),
        }
    )
    with tempfile.TemporaryDirectory(prefix="phase6a_guided_offsets_") as temporary_directory:
        temporary_path = Path(temporary_directory) / "evidence_offsets.parquet"
        pq.write_table(offsets_table, temporary_path, compression="zstd")
        parquet_bytes = temporary_path.stat().st_size
    return {
        "rows": len(guided),
        "evidence_items": item_count,
        "evidence_characters": characters,
        "evidence_utf8_bytes": utf8_bytes,
        "case_sensitive_hits": case_sensitive_hits,
        "case_sensitive_hit_rate": case_sensitive_hits / item_count,
        "normalized_exact_hits": normalized_hits,
        "normalized_exact_hit_rate": normalized_hits / item_count,
        "ambiguous_normalized_hits": ambiguous_hits,
        "offsets_arrow_bytes": offsets_table.nbytes,
        "offsets_parquet_zstd_bytes": parquet_bytes,
        "source": "outputs/phase3/aspects_guided_qwen25_7b_l1_n200041.parquet",
    }


