def sha256_file(path: Path, block_size: int = 8 * 1024 * 1024) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(block_size), b""):
            digest.update(block)
    return digest.hexdigest()


def validate_workbooks(paths: Iterable[Path]) -> list[dict[str, Any]]:
    expected = {"S1_File.xlsx", "S2_File.xlsx", "S3_File.xlsx"}
    actual = {path.name for path in SUPPORTING.glob("*.xlsx")}
    if actual != expected:
        raise AssertionError(f"supporting_information must contain exactly {sorted(expected)}; found {sorted(actual)}")
    records = []
    for path in paths:
        workbook = load_workbook(path, read_only=False, data_only=True)
        if workbook.sheetnames[0] != "README":
            raise AssertionError(f"README is not the first sheet in {path.name}")
        sheet_rows = {}
        for worksheet in workbook.worksheets:
            headers = [cell.value for cell in next(worksheet.iter_rows(min_row=1, max_row=1))]
            if not headers or any(value is None or str(value).strip() == "" for value in headers):
                raise AssertionError(f"blank header in {path.name}/{worksheet.title}")
            if len(headers) != len(set(headers)):
                raise AssertionError(f"duplicate header in {path.name}/{worksheet.title}")
            if worksheet.merged_cells.ranges:
                raise AssertionError(f"merged cells violate single-header requirement in {path.name}/{worksheet.title}")
            sheet_rows[worksheet.title] = max(0, worksheet.max_row - 1)
        workbook.close()
        size = path.stat().st_size
        records.append({
            "path": path.relative_to(ROOT).as_posix(),
            "bytes": size,
            "mib": size / (1024 ** 2),
            "sha256": sha256_file(path),
            "under_20_mib": size < MAX_XLSX_BYTES,
            "sheets": sheet_rows,
        })
        if size >= MAX_XLSX_BYTES:
            raise AssertionError(f"{path.name} is {size:,} bytes, not under 20 MiB")
    return records


