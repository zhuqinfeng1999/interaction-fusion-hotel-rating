def write_workbook(
    path: Path,
    identifier: str,
    description: str,
    sheets: list[tuple[str, pd.DataFrame, str, str]],
) -> None:
    manifest = [(name, sheet_description, source) for name, _, sheet_description, source in sheets]
    path.parent.mkdir(parents=True, exist_ok=True)
    with pd.ExcelWriter(path, engine="openpyxl") as writer:
        clean_excel_frame(readme_frame(identifier, description, manifest)).to_excel(
            writer, sheet_name="README", index=False
        )
        for name, frame, _, _ in sheets:
            if len(name) > 31:
                raise ValueError(f"Excel sheet name is too long: {name}")
            if len(set(frame.columns)) != len(frame.columns):
                raise ValueError(f"duplicate headers in {identifier}/{name}")
            clean_excel_frame(frame).to_excel(writer, sheet_name=name, index=False)

    workbook = load_workbook(path)
    workbook.properties.title = identifier
    workbook.properties.creator = "Phase 6A reproducible assembly"
    for worksheet in workbook.worksheets:
        worksheet.freeze_panes = "A2"
        worksheet.auto_filter.ref = worksheet.dimensions
        worksheet.row_dimensions[1].height = 30
        for cell in worksheet[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="1F4E78")
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        for column_index in range(1, worksheet.max_column + 1):
            sample = [worksheet.cell(row, column_index).value for row in range(1, min(worksheet.max_row, 1000) + 1)]
            width = min(80, max(12, max((len(str(value)) for value in sample if value is not None), default=0) + 2))
            worksheet.column_dimensions[get_column_letter(column_index)].width = width
        for row in worksheet.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = Alignment(vertical="top", wrap_text=worksheet.title == "README")
    workbook.save(path)


def fold_mean_coefficients(coefficients: pd.DataFrame) -> pd.DataFrame:
    keys = ["model", "block", "feature"]
    grouped = coefficients.groupby(keys, dropna=False)
    result = grouped["estimate"].agg(
        fold_mean_estimate="mean",
        across_fold_sd="std",
        folds="count",
    ).reset_index()
    signs = grouped["estimate"].agg(
        positive_folds=lambda series: int((series > 0).sum()),
        negative_folds=lambda series: int((series < 0).sum()),
        zero_folds=lambda series: int((series == 0).sum()),
    ).reset_index()
    return result.merge(signs, on=keys, validate="one_to_one")


def interaction_pivot(interactions: pd.DataFrame, interaction_type: str) -> pd.DataFrame:
    selected = interactions[interactions["interaction_type"] == interaction_type]
    pivot = selected.pivot_table(index="segment", columns="aspect", values="estimate", aggfunc="mean")
    ordered = [aspect for aspect in ASPECTS if aspect in pivot.columns]
    return pivot.reindex(columns=ordered).reset_index()


